package com.tarak.basic;

public class DefaultSwitchCase {
	
	public static void main(String[] args) {
	int Score =4;
		switch( Score) {
		case 1:
			System.out.println("Score is 1");
			break;
		case 2:
			System.out.println("Score is 2");
			break;
		default:
			System.out.println("Default case");
		}
		}
	}

